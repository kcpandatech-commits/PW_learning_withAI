// Array basics
// An array stores multiple values in a single variable.

let marks = [85, 90, 78, 92, 88];

console.log(marks);
console.log(marks[0]); // first element
console.log(marks[marks.length - 1]); // last element
console.log(marks.length); // total elements

// Arrays can store mixed data, but similar data is usually cleaner.
let mixed = ["Aman", 21, true, null];
console.log(mixed);

